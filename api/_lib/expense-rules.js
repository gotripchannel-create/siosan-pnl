// Общие бизнес-правила категоризации расходов — единый источник правды для всех
// serverless-функций (раньше эта логика была продублирована почти дословно в 5+
// файлах: api/iiko-expenses.js, api/iiko-day-report.js (дважды), api/iiko-dashboard.js,
// api/cron-sync-invoices.js, api/parse-report.js, api/vk-callback.js — правка в одном
// месте не долетала до остальных, из-за чего одни и те же баги приходилось чинить
// по нескольку раз). Теперь все эти файлы импортируют логику отсюда.

// Комментарий "зп" может быть с именем сотрудника ("зп курьер", "зп орхан",
// "рома зп") — считаем зарплатной выплатой, если "зп" встречается отдельным словом
// в любом месте комментария, а не только когда комментарий равен ровно "зп".
export const isSalaryComment = (s) => String(s || '').toLowerCase().trim().split(/\s+/).includes('зп');

// Фиксированный список категорий закупок кухни/бара — тот же, что в ручном
// интерфейсе (App.jsx, редактор категории для kitchenExpenses). ИИ обязан выбирать
// РОВНО одно из этих названий (см. промпт в parse-report.js/vk-callback.js), а эта
// функция — подстраховка на случай, если модель всё же вернёт что-то другое, а
// также для нормализации уже сохранённых ранее записей со старыми формулировками.
export const KITCHEN_CATEGORIES = ['Продукты', 'Напитки', 'Хозтовары кухни', 'Ремонт оборудования', 'Прочее'];

export function normalizeKitchenCategory(raw) {
  const trimmed = String(raw || '').trim();
  const exact = KITCHEN_CATEGORIES.find((c) => c.toLowerCase() === trimmed.toLowerCase());
  if (exact) return exact;
  const s = trimmed.toLowerCase();
  if (/продукт|закуп|еда|ингредиент|сырь|мясо|овощ|рыба|молоч|бакале|фрукт/.test(s)) return 'Продукты';
  if (/напит|вода|сок\b|пиво|вино|кола|лимонад|чай|кофе/.test(s)) return 'Напитки';
  if (/ремонт|поломк|запчаст|мастер/.test(s)) return 'Ремонт оборудования';
  if (/хозтовар|бытов|уборк|моющ|перчатк|пакет|стакан|салфет|канцеляр|расходник/.test(s)) return 'Хозтовары кухни';
  return 'Прочее';
}

// Разбивает одну выплату курьеру («ЗП КУРЬЕР 3500») на фиксированную ставку и бензин
// (остаток сверху).
export function splitCourierPayout(totalPay, fixedRate) {
  const total = Number(totalPay) || 0;
  const fixed = Number(fixedRate) || 2500;
  return { pay: Math.min(total, fixed), fuel: Math.max(0, total - fixed) };
}

// Общий фильтр "не расход/не выручка" для сырых проводок из iiko: "дб" — сверка
// кассы, "зп..." — зарплата (учитывается отдельно через ФОТ), "бк" — перенос остатка
// между сменами, "ошибка" — кассир сам пометил операцию как ошибочную, "закрытие
// кассовой смены" — системная запись.
export function isExcludedComment(comment) {
  const c = String(comment || '').trim().toLowerCase();
  return c === 'дб' || isSalaryComment(c) || c === 'бк' || c === 'ошибка' || c.startsWith('закрытие кассовой смены');
}
